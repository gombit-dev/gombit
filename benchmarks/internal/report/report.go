// Package report renders the root README's `## Performance` block from the
// committed benchmark outputs (results.json, footprint.json, metadata.json) and
// replaces the content between the benchmark-results markers. Generation is
// one-directional (issue #141 §9: Markdown is derived, never hand-authored), so
// `make benchmark-report` writes it and `make benchmark-report-check` (InSync)
// reports drift when the committed README no longer matches the data. CI runs
// that check (the `benchmark-report-drift` job in .github/workflows/ci.yml).
//
// The CRUD table reuses benchmarks/internal/summary for the per-(framework,
// concurrency) median, so the headline figure here and in summary.md come from
// the same code.
package report

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/gombit-dev/gombit/benchmarks/internal/footprint"
	"github.com/gombit-dev/gombit/benchmarks/internal/metadata"
	"github.com/gombit-dev/gombit/benchmarks/internal/microbench"
	"github.com/gombit-dev/gombit/benchmarks/internal/result"
	"github.com/gombit-dev/gombit/benchmarks/internal/summary"
)

const (
	// StartMarker / EndMarker bracket the generated block in README.md. They are
	// HTML comments so they render invisibly.
	StartMarker = "<!-- benchmark-results:start -->"
	EndMarker   = "<!-- benchmark-results:end -->"

	// crudBenchmark is the headline workload whose rows feed the CRUD table.
	crudBenchmark = "crud-list"

	// HeadlineConcurrency is the client count the README CRUD table publishes
	// (issue #141 §13 B is a single headline row, not a per-concurrency dump).
	// If a run doesn't have this level, the table falls back to the highest
	// concurrency present; the caption always states which was used.
	HeadlineConcurrency = 100

	// headlineScenario is the microbenchmark scenario the framework-tax ladder
	// publishes: the validated typed-handler POST (issue #141 §13 A's "validated
	// POST or equivalent representative typed-handler path" — not the Hello-World
	// GET, which would compress the overhead). The other four scenarios live in
	// microbench.json / the full report.
	headlineScenario = "valid-post"
)

// stackLadder is the abstraction order (thinnest → thickest) and the display
// name for each framework-tax stack.
var stackLadder = []struct{ key, name string }{
	{"nethttp", "net/http"}, {"gin", "Gin"}, {"huma", "Huma + Gin"}, {"gombit", "Gombit"},
}

// Protocol is the sweep shape (concurrency ladder, trials, per-trial duration,
// warm-up) that defines a run. It exists so a snapshot's actual protocol (from
// metadata) can be compared against the canonical one.
type Protocol struct {
	Concurrency     []int
	Trials          int
	DurationSeconds float64
	WarmupSeconds   float64
}

// CanonicalProtocol is the full dedicated-host run the methodology describes
// (issue #141 §13), pinned in benchmarks/config/versions.env. A snapshot whose
// metadata differs from this is labelled a reduced development snapshot in the
// generated README so its numbers are never mistaken for the canonical run.
// report_test.go asserts these stay in sync with versions.env, so the single
// source of truth (the env file) can't drift away from this comparison silently.
var CanonicalProtocol = Protocol{
	Concurrency:     []int{1, 10, 100, 500, 1000},
	Trials:          5,
	DurationSeconds: 30,
	WarmupSeconds:   10,
}

// Render returns the Markdown block (without the markers) for the given data.
// Any section with no data renders an honest "not yet recorded" line rather
// than an empty table, so the generator is runnable before the canonical run.
func Render(results []result.Result, prints []footprint.Footprint, micro []microbench.Row, meta metadata.Metadata) string {
	// A CRUD unit recorded before protocols were per unit is described by the
	// top-level protocol, the same answer every producer reads (metadata.ReadJSON).
	meta = meta.WithLegacyProtocols()
	// Tables first: the status banner judges publishability by the units the
	// tables actually caption, which only the table writers know.
	var tables strings.Builder
	published := map[string][]string{
		metadata.GroupMicrobench: writeFrameworkTaxTable(&tables, micro, meta),
		metadata.GroupCRUD:       writeCRUDTable(&tables, results, meta),
		metadata.GroupFootprint:  writeFootprintTable(&tables, prints, meta),
	}

	var b strings.Builder
	crudProtocols := protocolsOf(meta, published[metadata.GroupCRUD])
	writeStatusBanner(&b, meta, published, crudProtocols)
	b.WriteString("_Generated by `make benchmark-report` from `benchmarks/results/latest/` — do not edit by hand._\n\n")
	b.WriteString("Every framework within a table was measured on one host, closed-loop, under fixed ")
	b.WriteString("resource limits. The tables come from three separate runs of very different cost, so ")
	b.WriteString("each states the commit, host and toolchain **it** was measured at and figures are not ")
	b.WriteString("comparable across tables. Read ")
	b.WriteString("[benchmarks/docs/methodology.md](benchmarks/docs/methodology.md) — especially its ")
	b.WriteString("\"How not to interpret these results\" section — before citing any figure.\n\n")

	b.WriteString(tables.String())
	writeMethodology(&b, meta, crudProtocols)
	return b.String()
}

// writeProvenance captions a rendered table with the source state and machine
// that produced it, derived from the units that table actually publishes.
//
// It is written per table, not once per snapshot, because the measurement groups
// are produced by different targets at different times: a single snapshot-wide
// commit line silently vouched for measurements that never ran at that commit,
// which is how the framework-tax table came to publish pre-PERF-1 numbers under
// a caption implying otherwise (issue #266).
//
// And it is derived per UNIT, not per group, because these data files merge
// row-wise and subset runs are supported. Six footprint rows measured at commit
// A, then `APPS=gombit make benchmark-footprint` at B, must not caption the five
// untouched rows as B. When the units disagree the caption refuses to make one
// table-wide claim and states each unit instead — the same shape writeResourceLimits
// uses for per-app limit verdicts, and for the same reason.
//
// It is called only after a table actually rendered — a "not yet recorded"
// placeholder has no provenance to state.
func writeProvenance(b *strings.Builder, meta metadata.Metadata, group string, units []string) {
	sorted := uniqueSorted(units)
	if len(sorted) == 0 {
		// No rows were published, so there is nothing to attribute. Callers only
		// reach here after rendering a table, but a caption that invented a
		// provenance for an empty table would be exactly the wrong failure.
		return
	}
	provs, comparable := meta.UnitsProvenance(group, sorted)
	if comparable {
		writeProvenanceLine(b, provs[sorted[0]], timestampSpan(provs, sorted))
		return
	}

	parts := make([]string, len(sorted))
	for i, u := range sorted {
		p := provs[u]
		if p.Empty() {
			parts[i] = u + " at an unrecorded commit"
			continue
		}
		parts[i] = fmt.Sprintf("%s at `%s`%s (%s)", u, short(p.GitCommit), dirtySuffix(p.GitDirty), orDash(p.Timestamp))
	}
	fmt.Fprintf(b, "_**Rows were not measured together** — this table mixes source states, so its rows "+
		"are not comparable with each other: %s._\n\n", strings.Join(parts, "; "))
}

// uniqueSorted de-duplicates and orders unit names so a caption lists each unit
// once, in a stable order (the generated Markdown is diffed by CI).
func uniqueSorted(units []string) []string {
	seen := make(map[string]bool, len(units))
	out := make([]string, 0, len(units))
	for _, u := range units {
		if u == "" || seen[u] {
			continue
		}
		seen[u] = true
		out = append(out, u)
	}
	sort.Strings(out)
	return out
}

// writeProvenanceLine states one provenance in full. It carries the whole host
// description the shared "How these were measured" block used to print once:
// dropping kernel/arch/RAM to shorten the caption would leave a published table
// without enough metadata to reproduce it, which is the invariant
// benchmarks/internal/metadata exists to hold.
func writeProvenanceLine(b *strings.Builder, prov metadata.Provenance, when string) {
	if prov.Empty() {
		b.WriteString("_Measured at an unrecorded commit and host — no provenance was recorded for these rows._\n\n")
		return
	}
	fmt.Fprintf(b, "_Measured at `%s`%s, %s — %s, %d logical CPUs, %.1f GiB RAM (%s/%s, kernel %s), %s._\n\n",
		short(prov.GitCommit), dirtySuffix(prov.GitDirty), orDash(when),
		orDash(prov.CPUModel), prov.LogicalCPUs, gib(prov.RAMBytes),
		orDash(prov.OS), orDash(prov.Arch), orDash(prov.Kernel), orDash(prov.GoVersion))
}

// timestampSpan describes when a set of comparable units was measured. One run
// measures its units in sequence, so their timestamps legitimately differ by
// minutes; the caption states the span rather than picking one unit's clock and
// implying the others share it.
func timestampSpan(provs map[string]metadata.Provenance, units []string) string {
	first, last := "", ""
	for _, u := range units {
		ts := provs[u].Timestamp
		if ts == "" {
			continue
		}
		if first == "" || ts < first {
			first = ts
		}
		if ts > last {
			last = ts
		}
	}
	if first == last {
		return first
	}
	return first + " to " + last
}

// writeStatusBanner prints, at the very top of the block, the three conditions
// that make a snapshot unfit to advertise as the canonical benchmark:
//
//   - a dirty working tree — the numbers aren't tied to a committed source
//     state, so they aren't reproducible and must not be cited at all;
//   - a reduced protocol — a narrower sweep than the canonical dedicated-host
//     run, i.e. a development sample, not the published result; and
//   - a host not declared dedicated — the canonical protocol run on a
//     developer laptop is still a development sample (issue #291).
//
// The protocol is judged from the CRUD units the table renders (#377): each unit
// records the protocol its own rows ran under, so another workload's reduced run
// neither stamps a canonical table nor hides behind it.
//
// All are loud, quoted callouts so a reader skimming the README can't mistake
// a local/dev snapshot for the real thing (issue #141 §13). The dirty check
// covers every published unit, not just the top-level record: one table's rows
// measured against uncommitted source taint the block, because a reader
// skimming it cannot tell which group produced which table. Units no table
// publishes — the ablation ladder, an embedded footprint variant — are not
// judged: their dirt says nothing about the numbers on the page.
func writeStatusBanner(b *strings.Builder, meta metadata.Metadata, published map[string][]string, crud []protocolGroup) {
	if targets, dirty := dirtyTargets(meta, published); dirty {
		b.WriteString("> ## ⚠️ UNPUBLISHABLE DEVELOPMENT RUN\n>\n")
		b.WriteString("> Generated from a **dirty working tree** (uncommitted changes), so these ")
		b.WriteString("numbers are **not reproducible** and must not be cited. Commit the tree and ")
		b.WriteString("re-run " + rerunAdvice(targets) + " before publishing.\n\n")
	}
	if reduced, diffs := reducedFrom(crud); reduced > 0 {
		b.WriteString("> ### Reduced development snapshot\n>\n")
		switch {
		case len(crud) == 1:
			b.WriteString("> This run used a ")
		case reduced == len(crud):
			b.WriteString("> Every published row was measured under a ")
		default:
			b.WriteString("> Some published rows were measured under a ")
		}
		b.WriteString("**narrower protocol than the canonical dedicated-host run** ")
		b.WriteString("(pinned in `benchmarks/config/versions.env`; see ")
		b.WriteString("[benchmarks/docs/methodology.md](benchmarks/docs/methodology.md)): it is a ")
		b.WriteString("development sample, not the published benchmark. Differs in ")
		b.WriteString(strings.Join(diffs, "; "))
		b.WriteString(".\n\n")
	}
	if targets, classes := nonDedicatedTargets(meta, published); len(targets) > 0 {
		b.WriteString("> ### Not measured on dedicated hardware\n>\n")
		b.WriteString("> These tables were not all measured on a host declared as **dedicated benchmark ")
		b.WriteString("hardware** (recorded host class: " + strings.Join(classes, ", ") + "), so they are a ")
		b.WriteString("development sample, not the published benchmark — whatever protocol they ran. ")
		b.WriteString("Re-run the affected group(s) on a quiet, dedicated host with `" + metadata.HostClassEnv + "=")
		b.WriteString(metadata.HostClassDedicated + "` (`make " + strings.Join(targets, " ") + " benchmark-report`).\n\n")
	}
}

// nonDedicatedTargets returns the make targets of every group with a published
// unit not declared dedicated, and the distinct host classes those units
// recorded ("undeclared" for none). Only the classes metadata.ParseHostClass
// accepts are echoed: anything else in a hand-edited or older metadata.json is
// reported as unrecognised rather than pasted into the Markdown, where a stray
// backtick or newline would break the block. Unlike dirtyTargets it never consults the
// top-level record directly: collect-host-info rewrites it without measuring
// anything, so its class describes no row. A snapshot that records no unit is
// still judged by its top level, through UnitProvenance.
func nonDedicatedTargets(meta metadata.Metadata, published map[string][]string) (targets, classes []string) {
	seen := map[string]bool{}
	for _, g := range metadata.KnownGroups {
		units := meta.NonDedicatedUnits(g, published[g])
		if len(units) == 0 {
			continue
		}
		targets = append(targets, groupTargets[g])
		for _, u := range units {
			label := "`undeclared`"
			if class := meta.UnitProvenance(g, u).HostClass; class != "" {
				label = "an unrecognised value"
				if _, err := metadata.ParseHostClass(class); err == nil {
					label = "`" + class + "`"
				}
			}
			if !seen[label] {
				seen[label] = true
				classes = append(classes, label)
			}
		}
	}
	sort.Strings(classes)
	return targets, classes
}

// rerunChain is the ordered target list that regenerates a full snapshot on
// this branch. It is deliberately NOT `make benchmark` (the all-in-one target
// lands in a separate slice / PR #204); the banner must only name targets that
// exist in the tree it ships in, or its remediation command 404s.
const rerunChain = "make benchmark-crud-all benchmark-footprint benchmark-micro benchmark-report"

// groupTargets maps a measurement group to the make target that reproduces it.
var groupTargets = map[string]string{
	metadata.GroupMicrobench: "benchmark-micro",
	metadata.GroupCRUD:       "benchmark-crud-all",
	metadata.GroupFootprint:  "benchmark-footprint",
}

// dirtyTargets reports whether the block is unpublishable because of a dirty
// tree, and which make targets would clear it. targets is nil when the dirt
// cannot be pinned to specific groups: a dirty top-level record may describe
// any group, so over-prescribing is the safe direction.
func dirtyTargets(meta metadata.Metadata, published map[string][]string) (targets []string, dirty bool) {
	if meta.GitDirty != nil && *meta.GitDirty {
		return nil, true
	}
	for _, g := range metadata.KnownGroups {
		if meta.AnyUnitDirty(g, published[g]) {
			targets = append(targets, groupTargets[g])
		}
	}
	return targets, len(targets) > 0
}

// rerunAdvice names the smallest set of targets that actually has to be re-run.
// Once provenance is per unit, telling someone to re-run the hours-long CRUD
// sweep because the minutes-long microbenchmark was measured dirty would
// re-impose the exact cost coupling per-unit provenance removed (issue #266).
// With no targets it names the whole chain.
func rerunAdvice(targets []string) string {
	if len(targets) == 0 {
		return "the suite (`" + rerunChain + "`)"
	}
	return "the affected group(s) (`make " + strings.Join(targets, " ") + " benchmark-report`)"
}

// protocolGroup is a set of rendered units that were measured under one
// protocol, or that all recorded none (recorded == false).
type protocolGroup struct {
	units    []string
	params   metadata.RunParams
	recorded bool
}

// protocolsOf groups the given CRUD units by the protocol each one's rows were
// measured under (metadata.UnitRunParams), in unit order, so a table whose
// units agree is described once and a table that mixes protocols says which
// unit ran which.
func protocolsOf(meta metadata.Metadata, units []string) []protocolGroup {
	var groups []protocolGroup
	for _, u := range uniqueSorted(units) {
		params, ok := meta.UnitRunParams(metadata.GroupCRUD, u)
		placed := false
		for i := range groups {
			if groups[i].recorded == ok && (!ok || groups[i].params.Equal(params)) {
				groups[i].units = append(groups[i].units, u)
				placed = true
				break
			}
		}
		if !placed {
			groups = append(groups, protocolGroup{units: []string{u}, params: params, recorded: ok})
		}
	}
	return groups
}

// reducedFrom reports how many of the rendered protocol groups are narrower
// than (differ from) CanonicalProtocol, and a human-readable list of the
// differing dimensions, prefixed with the units when the table mixes protocols.
// A unit with no recorded protocol is not "reduced" — there is nothing to
// compare — so a pre-run placeholder returns 0.
func reducedFrom(groups []protocolGroup) (int, []string) {
	reduced := 0
	var diffs []string
	for _, g := range groups {
		if !g.recorded {
			continue
		}
		d := protocolDiffs(g.params)
		if len(d) > 0 {
			reduced++
		}
		switch {
		case len(d) == 0:
		case len(groups) == 1:
			diffs = append(diffs, d...)
		default:
			diffs = append(diffs, strings.Join(g.units, ", ")+": "+strings.Join(d, ", "))
		}
	}
	return reduced, diffs
}

// protocolDiffs lists how p differs from CanonicalProtocol.
func protocolDiffs(p metadata.RunParams) []string {
	var diffs []string
	if !equalInts(p.Concurrency, CanonicalProtocol.Concurrency) {
		diffs = append(diffs, fmt.Sprintf("concurrency %s (canonical %s)",
			concurrencyList(p.Concurrency), concurrencyList(CanonicalProtocol.Concurrency)))
	}
	if p.Trials != CanonicalProtocol.Trials {
		diffs = append(diffs, fmt.Sprintf("%s (canonical %s)",
			plural(p.Trials, "trial"), plural(CanonicalProtocol.Trials, "trial")))
	}
	if p.DurationSeconds != CanonicalProtocol.DurationSeconds {
		diffs = append(diffs, fmt.Sprintf("%s per trial (canonical %s)",
			seconds(p.DurationSeconds), seconds(CanonicalProtocol.DurationSeconds)))
	}
	if p.WarmupSeconds != CanonicalProtocol.WarmupSeconds {
		diffs = append(diffs, fmt.Sprintf("%s warm-up (canonical %s)",
			seconds(p.WarmupSeconds), seconds(CanonicalProtocol.WarmupSeconds)))
	}
	return diffs
}

func equalInts(a, b []int) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// writeFrameworkTaxTable is the issue's first README table (§13 A): the
// abstraction-cost ladder net/http → Gin → Huma → Gombit for the validated
// typed-handler POST, in median ns/op / B/op / allocs/op with a column relative
// to net/http — the headline question BENCH-1 exists to answer. It publishes the
// table only when all four rungs are present; a partial run renders an honest
// "incomplete" line rather than a ladder with holes.
func writeFrameworkTaxTable(b *strings.Builder, micro []microbench.Row, meta metadata.Metadata) []string {
	b.WriteString("### Framework tax — `net/http` → Gin → Huma → Gombit\n\n")
	b.WriteString("Per-request overhead of each layer on the same machine for the **validated typed POST** ")
	b.WriteString("(median ns/op, B/op, allocs/op; lower is better; `vs net/http` is the relative cost) — ")
	b.WriteString("the same-language, same-runtime cost of adopting Gombit. The other four scenarios ")
	b.WriteString("(plaintext, json, path-param, invalid-post) are in `benchmarks/results/latest/microbench.json`.\n\n")

	byStack := map[string]microbench.Row{}
	for _, r := range micro {
		if r.Scenario == headlineScenario {
			byStack[r.Stack] = r
		}
	}
	if len(byStack) == 0 {
		b.WriteString("_Not yet recorded — run `make benchmark-micro`._\n\n")
		return nil
	}
	// Fail closed: every rung must be present, or the ladder isn't publishable.
	for _, s := range stackLadder {
		if _, ok := byStack[s.key]; !ok {
			fmt.Fprintf(b, "_Incomplete — no `%s` row for the `%s` scenario; re-run `make benchmark-micro`._\n\n",
				s.key, headlineScenario)
			return nil
		}
	}
	baseline := byStack["nethttp"].MedianNsPerOp()

	b.WriteString("| stack | ns/op | B/op | allocs/op | vs net/http |\n")
	b.WriteString("| --- | ---: | ---: | ---: | ---: |\n")
	noisy := false
	for _, s := range stackLadder {
		r := byStack[s.key]
		flag := ""
		if r.CoVNsPerOp() > summary.DefaultCoVThreshold {
			flag = " ⚠"
			noisy = true
		}
		fmt.Fprintf(b, "| %s | %.0f%s | %d | %d | %s |\n",
			s.name, r.MedianNsPerOp(), flag, r.BytesPerOp, r.AllocsPerOp,
			microbench.Relative(r.MedianNsPerOp(), baseline))
	}
	if noisy {
		fmt.Fprintf(b, "\n⚠ marks a rung whose ns/op varied by more than %.0f%% across samples — a "+
			"noisy series (e.g. on a contended host); its median, and any ordering against a "+
			"neighbouring rung, should be distrusted.\n", summary.DefaultCoVThreshold*100)
	}
	b.WriteString("\n")
	// The four rungs are only comparable against each other when they share a
	// commit and a toolchain: the stdlib-only net/http rung has itself moved by
	// 3 allocs/op across Go releases with no source change. microbench.MergeStack
	// replaces one stack at a time, so the caption is derived from all four and
	// says so loudly if they diverge.
	stacks := make([]string, len(stackLadder))
	for i, s := range stackLadder {
		stacks[i] = s.key
	}
	writeProvenance(b, meta, metadata.GroupMicrobench, stacks)
	return stacks
}

func writeCRUDTable(b *strings.Builder, results []result.Result, meta metadata.Metadata) []string {
	b.WriteString("### PostgreSQL CRUD read — `GET /api/projects?page=1&limit=20`\n\n")

	groups := summary.Summarize(results, summary.DefaultCoVThreshold)
	conc := pickConcurrency(groups)
	if conc == 0 {
		b.WriteString("_Not yet recorded — run `make benchmark-crud-all`._\n\n")
		return nil
	}
	fmt.Fprintf(b, "At **%d concurrent clients**, median across trials: throughput (higher is better) "+
		"and tail latency (lower is better). p50/p95/p99 are the median across trials of each per-trial "+
		"percentile; ⚠ marks a group whose throughput varied by more than %.0f%% across trials — read its "+
		"row with care.\n\n", conc, summary.DefaultCoVThreshold*100)

	rows := make([]summary.Group, 0)
	for _, g := range groups {
		if g.Benchmark == crudBenchmark && g.Concurrency == conc {
			rows = append(rows, g)
		}
	}
	sort.SliceStable(rows, func(i, j int) bool { return rows[i].Framework < rows[j].Framework })

	b.WriteString("| framework | req/s | p50 ms | p95 ms | p99 ms |\n")
	b.WriteString("| --- | ---: | ---: | ---: | ---: |\n")
	for _, g := range rows {
		flag := ""
		if g.HighVariance {
			flag = " ⚠"
		}
		fmt.Fprintf(b, "| %s | %.0f%s | %.1f | %.1f | %.1f |\n",
			g.Framework, g.RequestsPerSecond.Median, flag,
			g.LatencyP50.Median, g.LatencyP95.Median, g.LatencyP99.Median)
	}
	b.WriteString("\n")
	// Units are the rendered rows' own merge keys (framework:benchmark), not every
	// framework in the file: run-crud replaces one app's workload at a time and
	// APPS= subsetting is a supported run, so the caption must be derived from
	// exactly what is rendered — and another workload's run for the same app must
	// not relabel it (#361).
	units := make([]string, len(rows))
	for i, g := range rows {
		units[i] = result.ProvenanceUnit(g.Framework, g.Benchmark)
	}
	writeProvenance(b, meta, metadata.GroupCRUD, units)
	return units
}

// pickConcurrency returns HeadlineConcurrency if any crud-list group has it,
// else the highest concurrency present, else 0 (no data).
func pickConcurrency(groups []summary.Group) int {
	present := map[int]bool{}
	maxC := 0
	for _, g := range groups {
		if g.Benchmark != crudBenchmark {
			continue
		}
		present[g.Concurrency] = true
		if g.Concurrency > maxC {
			maxC = g.Concurrency
		}
	}
	if present[HeadlineConcurrency] {
		return HeadlineConcurrency
	}
	return maxC
}

func writeFootprintTable(b *strings.Builder, prints []footprint.Footprint, meta metadata.Metadata) []string {
	b.WriteString("### Operational footprint\n\n")
	b.WriteString("Container-start cold start (median) and memory — lower is better. CPU is the ")
	b.WriteString("median percent one container drew during the closed-loop load (100 = one core); ")
	b.WriteString("it is *not* a quality score — a faster app that does more work in the window can ")
	b.WriteString("show higher CPU, so read it against the throughput row.\n\n")

	rows := make([]footprint.Footprint, 0, len(prints))
	for _, f := range prints {
		if f.Variant == footprint.VariantContainer {
			rows = append(rows, f)
		}
	}
	if len(rows) == 0 {
		b.WriteString("_Not yet recorded — run `make benchmark-footprint`._\n\n")
		return nil
	}
	sort.SliceStable(rows, func(i, j int) bool { return rows[i].Framework < rows[j].Framework })

	b.WriteString("| framework | cold start (ms) | idle (MB) | loaded (MB) | CPU (%) | image (MB) |\n")
	b.WriteString("| --- | ---: | ---: | ---: | ---: | ---: |\n")
	for _, f := range rows {
		fmt.Fprintf(b, "| %s | %.0f | %.1f | %.1f | %.0f | %.1f |\n",
			f.Framework, f.ColdStart.MedianMs, mib(f.IdleRSSBytes), mib(f.LoadedRSSBytes),
			f.CPUPercentUnderLoad, mib(f.ImageSizeBytes))
	}
	b.WriteString("\n")
	// Units are the rendered rows' own merge keys, so a re-measured embedded
	// variant never captions the container rows this table publishes.
	units := make([]string, len(rows))
	for i, f := range rows {
		units[i] = f.ProvenanceUnit()
	}
	writeProvenance(b, meta, metadata.GroupFootprint, units)
	return units
}

// writeMethodology prints the database, the applied resource limits, and the
// sweep protocol and load generator of the rows the CRUD table renders. The
// commit, host and toolchain are deliberately NOT here — they differ per
// measurement group and are captioned beneath each table instead
// (writeProvenance). A single global "Commit / date" line under three tables
// produced at three different commits is the misattribution issue #266 fixes.
//
// The protocol is per unit for the same reason (#377): it is read from the
// units the CRUD table renders, never from the snapshot-wide fields, which the
// last run-crud or `make benchmark-metadata` rewrote whatever it measured.
func writeMethodology(b *strings.Builder, meta metadata.Metadata, crud []protocolGroup) {
	b.WriteString("### How these were measured\n\n")
	// Keyed on what this block actually prints, not on the commit/host it no
	// longer prints. A snapshot that has group provenance but no shared run
	// parameters — what `make benchmark-micro` alone produces in a fresh
	// OUT_DIR — has nothing to say here, and must say so rather than render a
	// row of em-dashes with a "0 trials" that reads as a measured fact.
	if !hasSharedRunParameters(meta, crud) {
		b.WriteString("_Run metadata not yet recorded._\n\n")
		return
	}
	fmt.Fprintf(b, "- **PostgreSQL:** %s\n", orDash(meta.PostgresVersion))
	writeResourceLimits(b, meta)
	// The actual protocol the published rows ran, printed so a reduced/local run
	// cannot silently wear the canonical 5×30s / 1..1000 sweep the methodology
	// describes (issue #141 §13: the reader must not mistake the numbers for
	// universal constants).
	writeProtocol(b, crud)
}

// writeProtocol prints one Protocol line and one Load generator line when every
// rendered unit agrees on it, and names each unit's own otherwise, so no unit is
// described under parameters it was not measured with.
func writeProtocol(b *strings.Builder, crud []protocolGroup) {
	const notRecorded = "not recorded"
	protocols, tools := map[string][]string{}, map[string][]string{}
	for _, g := range crud {
		protocol, tool := notRecorded, notRecorded
		if g.recorded {
			protocol, tool = protocolText(g.params), orDash(g.params.BenchmarkTool)
		}
		protocols[protocol] = append(protocols[protocol], g.units...)
		tools[tool] = append(tools[tool], g.units...)
	}
	if len(crud) == 0 {
		protocols[notRecorded], tools[notRecorded] = nil, nil
	}
	b.WriteString(perUnitLine("Protocol", protocols) + "\n")
	b.WriteString(perUnitLine("Load generator", tools) +
		". Full method: [benchmarks/docs/methodology.md](benchmarks/docs/methodology.md).\n\n")
}

// perUnitLine renders one methodology bullet: the value alone when every unit
// shares it, else each unit set's own value, ordered by unit.
func perUnitLine(label string, values map[string][]string) string {
	if len(values) == 1 {
		for v := range values {
			return fmt.Sprintf("- **%s:** %s", label, v)
		}
	}
	parts := make([]string, 0, len(values))
	for v, units := range values {
		parts = append(parts, strings.Join(uniqueSorted(units), ", ")+" — "+v)
	}
	sort.Strings(parts)
	return fmt.Sprintf("- **%s (per unit):** %s", label, strings.Join(parts, "; "))
}

func protocolText(p metadata.RunParams) string {
	return fmt.Sprintf("concurrency %s VUs, %s × %s each (warm-up %s)",
		concurrencyList(p.Concurrency), plural(p.Trials, "trial"),
		seconds(p.DurationSeconds), seconds(p.WarmupSeconds))
}

// hasSharedRunParameters reports whether anything the methodology block prints
// was recorded: the database, the resource limits, or a published unit's
// protocol.
func hasSharedRunParameters(meta metadata.Metadata, crud []protocolGroup) bool {
	for _, g := range crud {
		if g.recorded {
			return true
		}
	}
	return meta.PostgresVersion != "" ||
		meta.ResourceLimits != "" ||
		len(meta.ResourceLimitsByFramework) > 0 ||
		meta.PostgresResourceLimits != ""
}

// writeResourceLimits renders the applied cgroup budgets. The authoritative
// field is ResourceLimitsByFramework (the per-app verified verdict preserved
// across the merge). When every measured app got the same verdict it collapses
// to one line — but the label names *which* frameworks it covers, never "all
// apps": run-crud always records a per-framework entry, so a standalone or
// APPS="gin-gorm gombit" subset run also produces a uniform map, and claiming
// whole-suite coverage there would be a lie (uniformValue answers "these values
// are equal", not "we measured the whole suite"). A non-uniform map lists each
// app so a partial/not-applied on one can never hide behind another's enforced.
// The Postgres container's own verdict prints separately. Only when the map is
// empty (the metadata-only path, e.g. collect-host-info) does it fall back to
// the scalar.
func writeResourceLimits(b *strings.Builder, meta metadata.Metadata) {
	if len(meta.ResourceLimitsByFramework) == 0 {
		fmt.Fprintf(b, "- **Resource limits:** %s\n", orDash(meta.ResourceLimits))
		return
	}
	keys := make([]string, 0, len(meta.ResourceLimitsByFramework))
	for k := range meta.ResourceLimitsByFramework {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	// The verdict string already classifies enforced/partial/not-applied, so the
	// label deliberately does NOT assert "applied" (that would read "applied ...
	// not applied" on the standalone path's sentinel).
	if v, uniform := uniformValue(meta.ResourceLimitsByFramework); uniform {
		fmt.Fprintf(b, "- **Resource limits (%s):** %s\n", strings.Join(keys, ", "), v)
	} else {
		parts := make([]string, len(keys))
		for i, k := range keys {
			parts[i] = fmt.Sprintf("%s — %s", k, meta.ResourceLimitsByFramework[k])
		}
		fmt.Fprintf(b, "- **Resource limits (per app):** %s\n", strings.Join(parts, "; "))
	}
	if meta.PostgresResourceLimits != "" {
		fmt.Fprintf(b, "- **Postgres container limits:** %s\n", meta.PostgresResourceLimits)
	}
}

// uniformValue returns the shared value and true when every entry in m is
// identical (and m is non-empty), else "" and false.
func uniformValue(m map[string]string) (string, bool) {
	var first string
	seen := false
	for _, v := range m {
		if !seen {
			first, seen = v, true
			continue
		}
		if v != first {
			return "", false
		}
	}
	return first, seen
}

func concurrencyList(cs []int) string {
	if len(cs) == 0 {
		return "—"
	}
	parts := make([]string, len(cs))
	for i, c := range cs {
		parts[i] = strconv.Itoa(c)
	}
	return strings.Join(parts, "/")
}

func plural(n int, unit string) string {
	if n == 1 {
		return "1 " + unit
	}
	return strconv.Itoa(n) + " " + unit + "s"
}

func seconds(s float64) string {
	if s == 0 {
		return "—"
	}
	return strconv.FormatFloat(s, 'f', -1, 64) + "s"
}

// ReplaceBlock returns readme with the content between the markers replaced by
// block (a trailing newline is normalised). It errors if either marker is
// missing or they are out of order.
func ReplaceBlock(readme, block string) (string, error) {
	start := strings.Index(readme, StartMarker)
	end := strings.Index(readme, EndMarker)
	if start < 0 || end < 0 {
		return "", fmt.Errorf("README is missing the %s / %s markers", StartMarker, EndMarker)
	}
	if end < start {
		return "", fmt.Errorf("%s appears before %s", EndMarker, StartMarker)
	}
	afterStart := start + len(StartMarker)
	var out strings.Builder
	out.WriteString(readme[:afterStart])
	out.WriteString("\n")
	out.WriteString(strings.TrimRight(block, "\n"))
	out.WriteString("\n")
	out.WriteString(readme[end:])
	return out.String(), nil
}

// InSync reports whether the block currently between the markers in readme
// already equals what Render produced (trailing whitespace normalised) — i.e.
// true means no drift, so a caller reads `if !InSync { fail }`. A missing marker
// is treated as out of sync (returns false with the marker error).
func InSync(readme, block string) (bool, error) {
	updated, err := ReplaceBlock(readme, block)
	if err != nil {
		return false, err
	}
	return updated == readme, nil
}

func mib(b int64) float64 { return float64(b) / (1 << 20) }
func gib(b int64) float64 { return float64(b) / (1 << 30) }

func short(sha string) string {
	if len(sha) > 12 {
		return sha[:12]
	}
	return orDash(sha)
}

func dirtySuffix(dirty *bool) string {
	if dirty != nil && *dirty {
		return " (dirty)"
	}
	return ""
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}
